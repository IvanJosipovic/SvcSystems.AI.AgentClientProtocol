using System.Text;

namespace SvcSystems.AI.AgentClientProtocol.Generator;

internal static class ProtocolJsonRenderer
{
    private const string ProtocolNamespace = "SvcSystems.AI.AgentClientProtocol.Protocol.Generated";
    private const string SerializationNamespace = "SvcSystems.AI.AgentClientProtocol.Serialization";

    public static string Render(ProtocolSchemaModel model)
    {
        var classes = model.Types.OfType<ProtocolClassModel>().ToArray();
        var enums = model.Types.OfType<ProtocolEnumModel>().ToArray();
        var unions = model.Types.OfType<ProtocolUnionModel>().ToArray();
        var code = new StringBuilder("// <auto-generated />\n#nullable enable\n")
            .AppendLine("using System;")
            .AppendLine("using System.Buffers;")
            .AppendLine("using System.Collections.Generic;")
            .AppendLine("using System.Text.Json;")
            .AppendLine("using System.Text.Json.Serialization;")
            .Append("using ").Append(ProtocolNamespace).AppendLine(";")
            .AppendLine()
            .Append("namespace ").Append(SerializationNamespace).AppendLine(";")
            .AppendLine()
            .AppendLine("internal static class AcpGeneratedJson")
            .AppendLine("{")
            .AppendLine("    private static byte[] Serialize(Action<Utf8JsonWriter> write)")
            .AppendLine("    {")
            .AppendLine("        var buffer = new ArrayBufferWriter<byte>();")
            .AppendLine("        using (var writer = new Utf8JsonWriter(buffer)) write(writer);")
            .AppendLine("        return buffer.WrittenSpan.ToArray();")
            .AppendLine("    }")
            .AppendLine();

        foreach (var item in classes.Where(type => type.BaseType is null))
        {
            code.Append("    internal static byte[] Serialize(").Append(item.Name).Append(" value) => Serialize(writer => Write").Append(item.Name).AppendLine("(writer, value));");
        }
        foreach (var item in enums)
        {
            code.Append("    internal static byte[] Serialize(").Append(item.Name).Append(" value) => Serialize(writer => Write").Append(item.Name).AppendLine("(writer, value));");
        }
        foreach (var item in unions)
        {
            code.Append("    internal static byte[] Serialize(").Append(item.Name).Append(" value) => Serialize(writer => Write").Append(item.Name).AppendLine("(writer, value));");
        }
        code.AppendLine();

        foreach (var item in classes)
        {
            RenderClassWriter(code, item, classes, unions);
        }
        foreach (var item in enums) RenderEnumWriter(code, item);
        foreach (var item in unions) RenderUnionWriter(code, item, classes, unions);

        code.AppendLine("    private static void WriteValue(Utf8JsonWriter writer, JsonElement value) => value.WriteTo(writer);")
            .AppendLine("    private static void WriteValue(Utf8JsonWriter writer, string value) => writer.WriteStringValue(value);")
            .AppendLine("    private static void WriteValue(Utf8JsonWriter writer, bool value) => writer.WriteBooleanValue(value);")
            .AppendLine("    private static void WriteValue(Utf8JsonWriter writer, int value) => writer.WriteNumberValue(value);")
            .AppendLine("    private static void WriteValue(Utf8JsonWriter writer, uint value) => writer.WriteNumberValue(value);")
            .AppendLine("    private static void WriteValue(Utf8JsonWriter writer, long value) => writer.WriteNumberValue(value);")
            .AppendLine("    private static void WriteValue(Utf8JsonWriter writer, ulong value) => writer.WriteNumberValue(value);")
            .AppendLine("    private static void WriteValue(Utf8JsonWriter writer, double value) => writer.WriteNumberValue(value);")
            .AppendLine("    private static void WriteValue(Utf8JsonWriter writer, float value) => writer.WriteNumberValue(value);")
            .AppendLine("}");
        return code.ToString();
    }

    private static void RenderClassWriter(
        StringBuilder code,
        ProtocolClassModel model,
        IReadOnlyList<ProtocolClassModel> classes,
        IReadOnlyList<ProtocolUnionModel> unions)
    {
        code.Append("    private static void Write").Append(model.Name).Append("(Utf8JsonWriter writer, ").Append(model.Name).AppendLine(" value)")
            .AppendLine("    {");
        if (model.DiscriminatorName is not null)
        {
            code.AppendLine("        writer.WriteStartObject();")
                .AppendLine("        switch (value)")
                .AppendLine("        {");
            foreach (var item in model.DiscriminatorCases)
            {
                var derived = classes.Single(type => type.Name == item.TypeName);
                code.Append("            case ").Append(item.TypeName).Append(" derived:").AppendLine()
                    .Append("                writer.WriteString(").Append(Literal(model.DiscriminatorName)).Append(", ").Append(Literal(item.DiscriminatorValue)).AppendLine(");");
                RenderProperties(code, derived, classes, unions, "derived", "                ");
                code.AppendLine("                break;");
            }
            code.AppendLine("            default: throw new ArgumentOutOfRangeException(nameof(value));")
                .AppendLine("        }")
                .AppendLine("        writer.WriteEndObject();");
        }
        else
        {
            code.AppendLine("        writer.WriteStartObject();");
            RenderProperties(code, model, classes, unions, "value", "        ");
            code.AppendLine("        writer.WriteEndObject();");
        }
        code.AppendLine("    }").AppendLine();
    }

    private static void RenderProperties(
        StringBuilder code,
        ProtocolClassModel model,
        IReadOnlyList<ProtocolClassModel> classes,
        IReadOnlyList<ProtocolUnionModel> unions,
        string instance,
        string indent)
    {
        foreach (var property in model.Properties)
        {
            var expression = instance + "." + property.Identifier;
            if (property.TypeName.EndsWith("?", StringComparison.Ordinal))
            {
                if (!property.IsRequired)
                {
                    code.Append(indent).Append("if (").Append(expression).AppendLine(" is not null)")
                        .Append(indent).AppendLine("{")
                        .Append(indent).Append("    writer.WritePropertyName(").Append(Literal(property.WireName)).AppendLine(");");
                    var optionalType = property.TypeName.Substring(0, property.TypeName.Length - 1);
                    var optionalExpression = IsValueType(optionalType, unions) ? expression + ".Value" : expression + "!";
                    RenderWriteValue(code, optionalType, optionalExpression, classes, unions, indent + "    ");
                    code.Append(indent).AppendLine("}");
                    continue;
                }
                code.Append(indent).Append("writer.WritePropertyName(").Append(Literal(property.WireName)).AppendLine(");")
                    .Append(indent).Append("if (").Append(expression).AppendLine(" is null) writer.WriteNullValue();")
                    .Append(indent).AppendLine("else")
                    .Append(indent).AppendLine("{");
                var nonNullableType = property.TypeName.Substring(0, property.TypeName.Length - 1);
                var nonNullableExpression = IsValueType(nonNullableType, unions) ? expression + ".Value" : expression + "!";
                RenderWriteValue(code, nonNullableType, nonNullableExpression, classes, unions, indent + "    ");
                code.Append(indent).AppendLine("}");
                continue;
            }

            code.Append(indent).Append("writer.WritePropertyName(").Append(Literal(property.WireName)).AppendLine(");");
            RenderWriteValue(code, property.TypeName, expression, classes, unions, indent);
        }

        if (model.HasExtensionData)
        {
            code.Append(indent).Append("if (").Append(instance).AppendLine(".ExtensionData is not null)")
                .Append(indent).AppendLine("{")
                .Append(indent).Append("    foreach (var item in ").Append(instance).AppendLine(".ExtensionData)")
                .Append(indent).AppendLine("    {")
                .Append(indent).AppendLine("        writer.WritePropertyName(item.Key);")
                .Append(indent).AppendLine("        item.Value.WriteTo(writer);")
                .Append(indent).AppendLine("    }")
                .Append(indent).AppendLine("}");
        }
    }

    private static void RenderWriteValue(
        StringBuilder code,
        string type,
        string expression,
        IReadOnlyList<ProtocolClassModel> classes,
        IReadOnlyList<ProtocolUnionModel> unions,
        string indent)
    {
        if (type.StartsWith("List<", StringComparison.Ordinal))
        {
            var elementType = type.Substring(5, type.Length - 6);
            code.Append(indent).AppendLine("writer.WriteStartArray();")
                .Append(indent).Append("foreach (var item in ").Append(expression).AppendLine(")")
                .Append(indent).AppendLine("{");
            RenderWriteValue(code, elementType, "item", classes, unions, indent + "    ");
            code.Append(indent).AppendLine("}")
                .Append(indent).AppendLine("writer.WriteEndArray();");
            return;
        }
        if (type.StartsWith("Dictionary<string, ", StringComparison.Ordinal))
        {
            var valueType = type.Substring(19, type.Length - 20).Trim();
            code.Append(indent).AppendLine("writer.WriteStartObject();")
                .Append(indent).Append("foreach (var item in ").Append(expression).AppendLine(")")
                .Append(indent).AppendLine("{")
                .Append(indent).AppendLine("    writer.WritePropertyName(item.Key);");
            RenderWriteValue(code, valueType, "item.Value", classes, unions, indent + "    ");
            code.Append(indent).AppendLine("}")
                .Append(indent).AppendLine("writer.WriteEndObject();");
            return;
        }
        if (type == "JsonElement")
        {
            code.Append(indent).Append(expression).AppendLine(".WriteTo(writer);");
            return;
        }
        if (type == "string") { code.Append(indent).Append("writer.WriteStringValue(").Append(expression).AppendLine(");"); return; }
        if (type == "bool") { code.Append(indent).Append("writer.WriteBooleanValue(").Append(expression).AppendLine(");"); return; }
        if (type is "int" or "uint" or "long" or "ulong" or "double" or "float") { code.Append(indent).Append("writer.WriteNumberValue(").Append(expression).AppendLine(");"); return; }
        if (classes.Any(item => item.Name == type)) { code.Append(indent).Append("Write").Append(type).Append("(writer, ").Append(expression).AppendLine(");"); return; }
        if (unions.Any(item => item.Name == type)) { code.Append(indent).Append("Write").Append(type).Append("(writer, ").Append(expression).AppendLine(");"); return; }
        code.Append(indent).Append("Write").Append(type).Append("(writer, ").Append(expression).AppendLine(");");
    }

    private static void RenderEnumWriter(StringBuilder code, ProtocolEnumModel model)
    {
        code.Append("    private static void Write").Append(model.Name).Append("(Utf8JsonWriter writer, ").Append(model.Name).AppendLine(" value)")
            .AppendLine("    {")
            .AppendLine("        writer.WriteStringValue(value switch")
            .AppendLine("        {");
        foreach (var value in model.Values)
        {
            var identifier = Pascal(value);
            if (string.IsNullOrEmpty(identifier)) identifier = "Value";
            code.Append("            ").Append(model.Name).Append('.').Append(identifier).Append(" => ").Append(Literal(value)).AppendLine(",");
        }
        code.AppendLine("            _ => throw new ArgumentOutOfRangeException(nameof(value))")
            .AppendLine("        });")
            .AppendLine("    }")
            .AppendLine();
    }

    private static void RenderUnionWriter(
        StringBuilder code,
        ProtocolUnionModel model,
        IReadOnlyList<ProtocolClassModel> classes,
        IReadOnlyList<ProtocolUnionModel> unions)
    {
        code.Append("    private static void Write").Append(model.Name).Append("(Utf8JsonWriter writer, ").Append(model.Name).AppendLine(" value)")
            .AppendLine("    {");
        code.AppendLine("        switch (value)")
            .AppendLine("        {");
        for (var index = 0; index < model.Cases.Count; index++)
        {
            var caseName = model.Cases[index];
            code.Append("            case ").Append(caseName).Append(" caseValue:").AppendLine();
            RenderWriteValue(code, caseName, "caseValue", classes, unions, "                ");
            code.AppendLine("                break;");
        }
        code.AppendLine("            default: throw new ArgumentOutOfRangeException(nameof(value));")
            .AppendLine("        }")
            .AppendLine("    }")
            .AppendLine();
    }

    private static bool IsValueType(string type, IReadOnlyList<ProtocolUnionModel> unions) =>
        type is "bool" or "int" or "uint" or "long" or "ulong" or "double" or "float" or "JsonElement" || unions.Any(item => item.Name == type);

    private static string Literal(string value) => "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";

    private static string Pascal(string value) => string.Concat(value.Split(new[] { '_', '-', '.', ' ' }, StringSplitOptions.RemoveEmptyEntries).Select(part => char.ToUpperInvariant(part[0]) + part.Substring(1)));
}
