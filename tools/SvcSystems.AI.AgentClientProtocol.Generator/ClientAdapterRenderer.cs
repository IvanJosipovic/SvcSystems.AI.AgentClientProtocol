using System.Text;

namespace SvcSystems.AI.AgentClientProtocol.Generator;

internal static class ClientAdapterRenderer
{
    public static string Render(SchemaModel model)
    {
        var required = new[] { "ContentBlock", "ToolCallContent", "McpServer", "McpServerStdio", "McpServerHttp", "McpServerSse" };
        var missing = required.Where(name => model.Types.All(type => type.Name != name)).ToArray();
        if (missing.Length > 0) throw new InvalidOperationException("ACP client adapters require schema models: " + string.Join(", ", missing));

        return Header + Body;
    }

    private const string Header = "// <auto-generated />\n// Generated adapters for the pinned ACP schema.\n#nullable enable\n";

    private const string Body = """
using System;
using System.Collections.Generic;
using System.Linq;
using System.Text.Json;
using SvcSystems.AI.AgentClientProtocol.Protocol.Generated;

namespace SvcSystems.AI.AgentClientProtocol.Serialization;

internal static class ClientAdapters
{
    internal static AgentContentBlock ToAgentContent(ContentBlock content) => content switch
    {
        ContentBlockVariant0Text text => new PromptTextContent(text.Text),
        ContentBlockVariant1Image image => new PromptImageContent(image.Data, image.MimeType, image.Uri),
        ContentBlockVariant2Audio audio => new PromptAudioContent(audio.Data, audio.MimeType),
        ContentBlockVariant3ResourceLink link => new ResourceLinkContent(link.Name, link.Uri, link.Description, link.MimeType),
        ContentBlockVariant4Resource resource => resource.Resource switch
        {
            TextResourceContents text => new EmbeddedResourceContent(text.Uri, text.Text, null, text.MimeType),
            BlobResourceContents blob => new EmbeddedResourceContent(blob.Uri, null, blob.Blob, blob.MimeType),
            _ => throw new ProtocolException("ACP embedded resource did not match a known resource variant.")
        },
        UnknownWireContent unknown => new UnknownContent(ReadString(unknown.RawPayload, "type") ?? "unknown", unknown.RawPayload),
        _ => throw new ProtocolException("ACP content block did not match a known schema variant.")
    };

    internal static AgentContentBlock ToAgentToolCallContent(ToolCallContent content) => content switch
    {
        ToolCallContentVariant0Content nested => ToAgentContent(nested.Content),
        ToolCallContentVariant1Diff diff => new DiffContent(diff.Path, diff.OldText, diff.NewText),
        ToolCallContentVariant2Terminal terminal => new TerminalReference(terminal.TerminalId),
        _ => throw new ProtocolException("ACP tool call content did not match a known schema variant.")
    };

    internal static ContentBlock ToContentBlock(AgentContentBlock block) => block switch
    {
        PromptTextContent text => new ContentBlockVariant0Text { Text = text.Text },
        PromptImageContent image => new ContentBlockVariant1Image { Data = image.Data, MimeType = image.MimeType, Uri = image.Uri },
        PromptAudioContent audio => new ContentBlockVariant2Audio { Data = audio.Data, MimeType = audio.MimeType },
        ResourceLinkContent link => new ContentBlockVariant3ResourceLink { Name = link.Name, Uri = link.Uri, Description = link.Description, MimeType = link.MimeType },
        EmbeddedResourceContent resource => new ContentBlockVariant4Resource
        {
            Resource = resource.Blob is not null
                ? new BlobResourceContents { Blob = resource.Blob, MimeType = resource.MimeType, Uri = resource.Uri }
                : new TextResourceContents { Text = resource.Text ?? string.Empty, MimeType = resource.MimeType, Uri = resource.Uri }
        },
        UnknownContent unknown => new UnknownWireContent(unknown.RawPayload),
        _ => throw new ArgumentException($"Unsupported ACP prompt content type '{block.GetType().Name}'.", nameof(block))
    };

    internal static List<McpServer> ToMcpServers(IReadOnlyList<McpServerOptions> servers) => servers.Select(server => server switch
    {
        StdioMcpServerOptions stdio => (McpServer)new McpServerStdio
        {
            Name = stdio.Name, Command = stdio.Command, Args = stdio.Arguments?.ToList() ?? [],
            Env = stdio.Environment?.Select(item => new EnvVariable { Name = item.Key, Value = item.Value }).ToList() ?? [],
            ExtensionData = new Dictionary<string, JsonElement>(StringComparer.Ordinal) { ["type"] = JsonSerializer.SerializeToElement(Discriminators.ToWireValue(McpServerDiscriminator.Stdio), JsonContext.Default.String) }
        },
        HttpMcpServerOptions http => new McpServerHttp
        {
            Name = http.Name, Url = http.Url, Headers = ToHeaders(http.Headers),
            ExtensionData = new Dictionary<string, JsonElement>(StringComparer.Ordinal) { ["type"] = JsonSerializer.SerializeToElement(Discriminators.ToWireValue(McpServerDiscriminator.Http), JsonContext.Default.String) }
        },
        SseMcpServerOptions sse => new McpServerSse
        {
            Name = sse.Name, Url = sse.Url, Headers = ToHeaders(sse.Headers),
            ExtensionData = new Dictionary<string, JsonElement>(StringComparer.Ordinal) { ["type"] = JsonSerializer.SerializeToElement(Discriminators.ToWireValue(McpServerDiscriminator.Sse), JsonContext.Default.String) }
        },
        _ => throw new ArgumentOutOfRangeException(nameof(servers), $"Unknown MCP server configuration type '{server.GetType().Name}'.")
    }).ToList();

    private static List<HttpHeader> ToHeaders(IReadOnlyDictionary<string, string>? headers) =>
        headers?.Select(item => new HttpHeader { Name = item.Key, Value = item.Value }).ToList() ?? [];

    private static string? ReadString(JsonElement element, string propertyName) =>
        element.ValueKind == JsonValueKind.Object && element.TryGetProperty(propertyName, out var value) && value.ValueKind == JsonValueKind.String ? value.GetString() : null;
}
""";
}
