using System.Text;

namespace SvcSystems.AI.AgentClientProtocol.Generator;

internal static class WireJsonRenderer
{
    private const string GeneratedNamespace = "SvcSystems.AI.AgentClientProtocol.Generated";
    private const string SerializationNamespace = "SvcSystems.AI.AgentClientProtocol.Serialization";

    internal static bool IsSystemTextJsonSafe(SchemaModel model, string typeName) =>
        model.Types.OfType<EnumModel>().Any(item => item.Name == typeName) ||
        CanUseSystemTextJson(typeName, model.Types.OfType<ClassModel>().ToArray(), model.Types.OfType<UnionModel>().ToArray(), new HashSet<string>(StringComparer.Ordinal));

    public static string Render(SchemaModel model, bool useSystemTextJsonContext)
    {
        var classes = model.Types.OfType<ClassModel>().ToArray();
        var enums = model.Types.OfType<EnumModel>().ToArray();
        var unions = model.Types.OfType<UnionModel>().ToArray();
        var stjSafeClasses = new HashSet<string>(classes
            .Where(item => CanUseSystemTextJson(item.Name, classes, unions, new HashSet<string>(StringComparer.Ordinal)))
            .Select(item => item.Name), StringComparer.Ordinal);
        var stjSafeUnions = new HashSet<string>(unions
            .Where(item => CanUseSystemTextJson(item.Name, classes, unions, new HashSet<string>(StringComparer.Ordinal)))
            .Select(item => item.Name), StringComparer.Ordinal);
        var code = new StringBuilder("// <auto-generated />\n#nullable enable\n")
            .AppendLine("using System;")
            .AppendLine("using System.Buffers;")
            .AppendLine("using System.Collections.Generic;")
            .AppendLine("using System.Text.Json;")
            .AppendLine("using System.Text.Json.Serialization;")
            .Append("using ").Append(GeneratedNamespace).AppendLine(";")
            .AppendLine()
            .Append("namespace ").Append(SerializationNamespace).AppendLine(";")
            .AppendLine()
            .AppendLine("internal static class GeneratedJson")
            .AppendLine("{")
            .AppendLine("    private static byte[] Serialize(Action<Utf8JsonWriter> write)")
            .AppendLine("    {")
            .AppendLine("        var buffer = new ArrayBufferWriter<byte>();")
            .AppendLine("        using (var writer = new Utf8JsonWriter(buffer)) write(writer);")
            .AppendLine("        return buffer.WrittenSpan.ToArray();")
            .AppendLine("    }")
            .AppendLine();

        foreach (var item in classes.Where(type => type.BaseType is null))
        {
            if (useSystemTextJsonContext && stjSafeClasses.Contains(item.Name))
            {
                code.Append("    internal static byte[] Serialize(").Append(item.Name).Append(" value) => JsonSerializer.SerializeToUtf8Bytes(value, JsonContext.Default.").Append(item.Name).AppendLine(");");
            }
            else
            {
                code.Append("    internal static byte[] Serialize(").Append(item.Name).Append(" value) => Serialize(writer => Write").Append(item.Name).AppendLine("(writer, value));");
            }
        }
        foreach (var item in enums)
        {
            if (useSystemTextJsonContext)
                code.Append("    internal static byte[] Serialize(").Append(item.Name).Append(" value) => JsonSerializer.SerializeToUtf8Bytes(value, JsonContext.Default.").Append(item.Name).AppendLine(");");
            else
                code.Append("    internal static byte[] Serialize(").Append(item.Name).Append(" value) => Serialize(writer => Write").Append(item.Name).AppendLine("(writer, value));");
        }
        foreach (var item in unions)
        {
            if (useSystemTextJsonContext && stjSafeUnions.Contains(item.Name))
                code.Append("    internal static byte[] Serialize(").Append(item.Name).Append(" value) => JsonSerializer.SerializeToUtf8Bytes(value, JsonContext.Default.").Append(item.Name).AppendLine(");");
            else
                code.Append("    internal static byte[] Serialize(").Append(item.Name).Append(" value) => Serialize(writer => Write").Append(item.Name).AppendLine("(writer, value));");
        }
        code.AppendLine();

        foreach (var item in classes)
        {
            RenderClassWriter(code, item, classes, unions);
        }
        foreach (var item in enums) RenderEnumWriter(code, item);
        foreach (var item in unions) RenderUnionWriter(code, item, classes, unions);

        var readableClasses = classes
            .Where(item => CanDeserializeClass(item, classes, unions, new HashSet<string>(StringComparer.Ordinal)))
            .ToArray();
        foreach (var item in readableClasses)
        {
            RenderClassReader(code, item, classes, unions, useSystemTextJsonContext && stjSafeClasses.Contains(item.Name));
        }
        foreach (var item in classes.Where(item => item.DiscriminatorName is not null && item.DiscriminatorCases.All(discriminatorCase => readableClasses.Any(type => type.Name == discriminatorCase.TypeName))))
            RenderTaggedUnionReader(code, item, useSystemTextJsonContext && stjSafeClasses.Contains(item.Name));
        if (useSystemTextJsonContext)
        {
            foreach (var item in unions.Where(item => stjSafeUnions.Contains(item.Name)))
                RenderSystemTextJsonUnionReader(code, item);
        }
        foreach (var item in unions.Where(item => (!useSystemTextJsonContext || !stjSafeUnions.Contains(item.Name)) && CanDeserializeUnion(item, readableClasses)))
            RenderUnionReader(code, item, readableClasses);
        foreach (var item in unions.Where(item => (!useSystemTextJsonContext || !stjSafeUnions.Contains(item.Name)) && CanDeserializeUnionValue(item, readableClasses)))
            RenderUnionValueReader(code, item, classes);
        foreach (var item in unions.Where(item => (!useSystemTextJsonContext || !stjSafeUnions.Contains(item.Name)) && !CanDeserializeUnion(item, readableClasses) && CanDeserializeUnionValue(item, readableClasses)))
            RenderTypedUnionValueReader(code, item);

        code.AppendLine("    private static void WriteValue(Utf8JsonWriter writer, JsonElement value) => value.WriteTo(writer);")
            .AppendLine("    private static void WriteValue(Utf8JsonWriter writer, string value) => writer.WriteStringValue(value);")
            .AppendLine("    private static void WriteValue(Utf8JsonWriter writer, bool value) => writer.WriteBooleanValue(value);")
            .AppendLine("    private static void WriteValue(Utf8JsonWriter writer, int value) => writer.WriteNumberValue(value);")
            .AppendLine("    private static void WriteValue(Utf8JsonWriter writer, uint value) => writer.WriteNumberValue(value);")
            .AppendLine("    private static void WriteValue(Utf8JsonWriter writer, long value) => writer.WriteNumberValue(value);")
            .AppendLine("    private static void WriteValue(Utf8JsonWriter writer, ulong value) => writer.WriteNumberValue(value);")
            .AppendLine("    private static void WriteValue(Utf8JsonWriter writer, double value) => writer.WriteNumberValue(value);")
            .AppendLine("    private static void WriteValue(Utf8JsonWriter writer, float value) => writer.WriteNumberValue(value);")
            .AppendLine("    private static JsonElement Required(JsonElement value, string name)")
            .AppendLine("    {")
            .AppendLine("        if (value.ValueKind != JsonValueKind.Object || !value.TryGetProperty(name, out var property) || property.ValueKind == JsonValueKind.Null)")
            .AppendLine("            throw new JsonException($\"Required property '{name}' is missing or null.\");")
            .AppendLine("        return property;")
            .AppendLine("    }")
            .AppendLine("    private static string ReadStringValue(JsonElement value) => value.ValueKind == JsonValueKind.String ? value.GetString()! : throw new JsonException(\"Expected a JSON string.\");")
            .AppendLine("    private static bool ReadBooleanValue(JsonElement value) => value.ValueKind is JsonValueKind.True or JsonValueKind.False ? value.GetBoolean() : throw new JsonException(\"Expected a JSON boolean.\");")
            .AppendLine("    private static int ReadInt32Value(JsonElement value) => value.TryGetInt32(out var result) ? result : throw new JsonException(\"Expected a 32-bit integer.\");")
            .AppendLine("    private static uint ReadUInt32Value(JsonElement value) => value.TryGetUInt32(out var result) ? result : throw new JsonException(\"Expected an unsigned 32-bit integer.\");")
            .AppendLine("    private static long ReadInt64Value(JsonElement value) => value.TryGetInt64(out var result) ? result : throw new JsonException(\"Expected a 64-bit integer.\");")
            .AppendLine("    private static ulong ReadUInt64Value(JsonElement value) => value.TryGetUInt64(out var result) ? result : throw new JsonException(\"Expected an unsigned 64-bit integer.\");")
            .AppendLine("    private static double ReadDoubleValue(JsonElement value) => value.TryGetDouble(out var result) ? result : throw new JsonException(\"Expected a number.\");")
            .AppendLine("    private static float ReadSingleValue(JsonElement value) => value.TryGetSingle(out var result) ? result : throw new JsonException(\"Expected a number.\");")
            .AppendLine("    private static List<T> ReadList<T>(JsonElement value, Func<JsonElement, T> read)")
            .AppendLine("    {")
            .AppendLine("        if (value.ValueKind != JsonValueKind.Array) throw new JsonException(\"Expected a JSON array.\");")
            .AppendLine("        var result = new List<T>();")
            .AppendLine("        foreach (var item in value.EnumerateArray()) result.Add(read(item));")
            .AppendLine("        return result;")
            .AppendLine("    }")
            .AppendLine("    private static Dictionary<string, string> ReadStringDictionary(JsonElement value)")
            .AppendLine("    {")
            .AppendLine("        if (value.ValueKind != JsonValueKind.Object) throw new JsonException(\"Expected a JSON object.\");")
            .AppendLine("        var result = new Dictionary<string, string>(StringComparer.Ordinal);")
            .AppendLine("        foreach (var item in value.EnumerateObject()) result.Add(item.Name, ReadStringValue(item.Value));")
            .AppendLine("        return result;")
            .AppendLine("    }")
            .AppendLine("    private static Dictionary<string, JsonElement> ReadElementDictionary(JsonElement value)")
            .AppendLine("    {")
            .AppendLine("        if (value.ValueKind != JsonValueKind.Object) throw new JsonException(\"Expected a JSON object.\");")
            .AppendLine("        var result = new Dictionary<string, JsonElement>(StringComparer.Ordinal);")
            .AppendLine("        foreach (var item in value.EnumerateObject()) result.Add(item.Name, item.Value.Clone());")
            .AppendLine("        return result;")
            .AppendLine("    }")
            .AppendLine("    private static Dictionary<string, JsonElement>? ReadExtensionData(JsonElement value, params string[] knownProperties)")
            .AppendLine("    {")
            .AppendLine("        var result = new Dictionary<string, JsonElement>(StringComparer.Ordinal);")
            .AppendLine("        foreach (var item in value.EnumerateObject())")
            .AppendLine("        {")
            .AppendLine("            if (Array.IndexOf(knownProperties, item.Name) < 0) result.Add(item.Name, item.Value.Clone());")
            .AppendLine("        }")
            .AppendLine("        return result.Count == 0 ? null : result;")
            .AppendLine("    }")
            .AppendLine("}");
        return code.ToString();
    }

    private static bool CanUseSystemTextJson(
        string typeName,
        IReadOnlyList<ClassModel> classes,
        IReadOnlyList<UnionModel> unions,
        HashSet<string> visiting)
    {
        var type = typeName.EndsWith("?", StringComparison.Ordinal) ? typeName.Substring(0, typeName.Length - 1) : typeName;
        if (type is "string" or "bool" or "int" or "uint" or "long" or "ulong" or "double" or "float" or "JsonElement") return true;
        if (type.StartsWith("List<", StringComparison.Ordinal))
            return CanUseSystemTextJson(type.Substring(5, type.Length - 6), classes, unions, visiting);
        if (type.StartsWith("Dictionary<string, ", StringComparison.Ordinal))
            return CanUseSystemTextJson(type.Substring("Dictionary<string, ".Length, type.Length - "Dictionary<string, ".Length - 1), classes, unions, visiting);
        var union = unions.FirstOrDefault(item => item.Name == type);
        if (union is not null)
        {
            if (!visiting.Add(type)) return true;
            var canUseUnion = CanClassifyUnionWithSystemTextJson(union, classes) &&
                union.Cases.All(item => CanUseSystemTextJson(item, classes, unions, visiting));
            visiting.Remove(type);
            return canUseUnion;
        }

        var model = classes.FirstOrDefault(item => item.Name == type);
        if (model is null) return false;
        if (model.AllowUnknownDiscriminator) return false;
        if (!visiting.Add(type)) return true;
        var canUse = (model.BaseType is null || CanUseSystemTextJson(model.BaseType, classes, unions, visiting)) &&
            (model.DiscriminatorName is null
                ? model.Properties.All(property => CanUseSystemTextJson(property.TypeName, classes, unions, visiting))
                : model.DiscriminatorCases.All(item => CanUseSystemTextJson(item.TypeName, classes, unions, visiting)));
        visiting.Remove(type);
        return canUse;
    }

    private static bool CanClassifyUnionWithSystemTextJson(UnionModel union, IReadOnlyList<ClassModel> classes)
    {
        if (union.Cases.Count <= 1) return true;

        // STJ's built-in structural classifier can distinguish object cases by
        // required property names (or by a shared const discriminator). It cannot
        // distinguish two array cases, or object cases with identical contracts.
        if (union.Cases.All(item => item.StartsWith("List<", StringComparison.Ordinal))) return false;

        var objectCases = new List<ClassModel>();
        var tokenKinds = new HashSet<string>(StringComparer.Ordinal);
        foreach (var caseName in union.Cases)
        {
            if (caseName.StartsWith("List<", StringComparison.Ordinal))
            {
                if (!tokenKinds.Add("array")) return false;
                continue;
            }

            var model = classes.FirstOrDefault(item => item.Name == caseName);
            if (model is not null)
            {
                objectCases.Add(model);
                continue;
            }

            var tokenKind = caseName switch
            {
                "string" => "string",
                "JsonElement" => "any",
                "bool" => "boolean",
                "int" or "uint" or "long" or "ulong" or "double" or "float" => "number",
                _ => "unsupported"
            };
            if (tokenKind == "unsupported" || tokenKind == "any" || !tokenKinds.Add(tokenKind)) return false;
        }

        if (objectCases.Count == 0) return true;
        if (objectCases.Count != union.Cases.Count) return false;

        return objectCases.All(candidate => candidate.Properties.Any(property => property.IsRequired &&
            objectCases.Where(other => !ReferenceEquals(other, candidate))
                .All(other => other.Properties.All(otherProperty => otherProperty.WireName != property.WireName))));
    }

    private static bool CanDeserializeClass(
        ClassModel model,
        IReadOnlyList<ClassModel> classes,
        IReadOnlyList<UnionModel> unions,
        HashSet<string> visiting)
    {
        if (model.DiscriminatorName is not null || !visiting.Add(model.Name)) return false;
        var canRead = model.Properties.All(property => CanDeserializeType(property.TypeName, classes, unions, visiting));
        visiting.Remove(model.Name);
        return canRead;
    }

    private static bool CanDeserializeType(string typeName, IReadOnlyList<ClassModel> classes, IReadOnlyList<UnionModel> unions, HashSet<string> visiting)
    {
        var type = typeName.EndsWith("?", StringComparison.Ordinal) ? typeName.Substring(0, typeName.Length - 1) : typeName;
        if (type is "string" or "bool" or "int" or "uint" or "long" or "ulong" or "double" or "float" or "JsonElement") return true;
        if (type.StartsWith("List<", StringComparison.Ordinal))
            return CanDeserializeType(type.Substring(5, type.Length - 6), classes, unions, visiting);
        if (type == "Dictionary<string, string>" || type == "Dictionary<string, JsonElement>") return true;
        var classModel = classes.FirstOrDefault(item => item.Name == type);
        if (classModel is not null)
        {
            if (classModel.DiscriminatorName is not null)
            {
                return classModel.DiscriminatorCases.All(item => CanDeserializeClass(
                    classes.Single(candidate => candidate.Name == item.TypeName), classes, unions, visiting));
            }
            return CanDeserializeClass(classModel, classes, unions, visiting);
        }
        var unionModel = unions.FirstOrDefault(item => item.Name == type);
        return unionModel is not null && CanDeserializeUnionValue(unionModel, classes);
    }

    private static bool CanDeserializeUnion(UnionModel model, IReadOnlyList<ClassModel> classes)
    {
        if (model.Cases.Count == 0 || model.Cases.Any(caseName => classes.All(type => type.Name != caseName))) return false;
        var variants = model.Cases.Select(caseName => classes.Single(type => type.Name == caseName)).ToArray();
        return variants[0].Properties.Any(property => property.ConstValue is not null && variants.All(variant =>
            variant.Properties.Any(candidate => candidate.WireName == property.WireName && candidate.ConstValue is not null)) &&
            variants.Select(variant => variant.Properties.Single(candidate => candidate.WireName == property.WireName).ConstValue).Distinct(StringComparer.Ordinal).Count() == variants.Length);
    }

    private static bool CanDeserializeUnionValue(UnionModel model, IReadOnlyList<ClassModel> classes)
    {
        if (model.Cases.Count == 0) return false;
        if (model.Cases.All(caseName => caseName.StartsWith("List<", StringComparison.Ordinal)))
        {
            return model.Cases.All(caseName =>
            {
                var itemType = caseName.Substring(5, caseName.Length - 6);
                return classes.Any(type => type.Name == itemType);
            });
        }
        if (!model.StructuralClassifier && !CanDeserializeUnion(model, classes)) return false;
        return model.Cases.All(caseName =>
        {
            if (caseName.StartsWith("List<", StringComparison.Ordinal))
            {
                var itemType = caseName.Substring(5, caseName.Length - 6);
                return classes.Any(type => type.Name == itemType);
            }
            return classes.Any(type => type.Name == caseName);
        });
    }

    private static void RenderUnionValueReader(StringBuilder code, UnionModel model, IReadOnlyList<ClassModel> classes)
    {
        code.Append("    internal static object Deserialize").Append(model.Name).AppendLine("Value(JsonElement value)")
            .AppendLine("    {");
        if (model.Cases.All(caseName => caseName.StartsWith("List<", StringComparison.Ordinal)))
        {
            code.AppendLine("        if (value.ValueKind != JsonValueKind.Array) throw new JsonException(\"Expected a JSON array.\");")
                .AppendLine("        if (value.GetArrayLength() == 0)")
                .Append("            return ").Append(ReadValueExpression(model.Cases[0], "value", classes, Array.Empty<UnionModel>())).AppendLine(";");
            var itemTypes = model.Cases.Select(caseName => caseName.Substring(5, caseName.Length - 6))
                .Select(itemType => classes.Single(type => type.Name == itemType)).ToArray();
            for (var index = 0; index < itemTypes.Length; index++)
            {
                var uniqueRequired = itemTypes[index].Properties.FirstOrDefault(property => property.IsRequired && itemTypes
                    .Where((_, otherIndex) => otherIndex != index)
                    .All(other => other.Properties.All(candidate => candidate.WireName != property.WireName)));
                if (uniqueRequired is null) continue;
                code.Append("        if (value[0].TryGetProperty(").Append(Literal(uniqueRequired.WireName)).Append(", out _)) return ")
                    .Append(ReadValueExpression(model.Cases[index], "value", classes, Array.Empty<UnionModel>())).AppendLine(";");
            }
            code.AppendLine("        throw new JsonException(\"Array did not match any union case.\");")
                .AppendLine("    }").AppendLine();
            return;
        }

        if (model.StructuralClassifier)
        {
            code.AppendLine("        if (value.ValueKind != JsonValueKind.Object) throw new JsonException(\"Expected a JSON object.\");");
            var variants = model.Cases.Select(caseName => classes.Single(type => type.Name == caseName)).ToArray();
            var discriminator = variants[0].Properties.FirstOrDefault(property => property.ConstValue is not null && variants.All(variant =>
                variant.Properties.Any(candidate => candidate.WireName == property.WireName && candidate.ConstValue is not null)) &&
                variants.Select(variant => variant.Properties.Single(candidate => candidate.WireName == property.WireName).ConstValue)
                    .Distinct(StringComparer.Ordinal).Count() == variants.Length);
            if (discriminator is not null)
            {
                code.Append("        if (value.TryGetProperty(").Append(Literal(discriminator.WireName)).AppendLine(", out var discriminatorValue))")
                    .AppendLine("        {")
                    .AppendLine("            return ReadStringValue(discriminatorValue) switch")
                    .AppendLine("            {");
                foreach (var variant in variants)
                {
                    var constValue = variant.Properties.Single(property => property.WireName == discriminator.WireName).ConstValue!;
                    code.Append("                ").Append(Literal(constValue)).Append(" => Deserialize").Append(variant.Name).AppendLine("(value),");
                }
                code.AppendLine("                _ => throw new JsonException(\"Unknown discriminator value.\")")
                    .AppendLine("            };")
                    .AppendLine("        }");
            }
            for (var index = 0; index < model.Cases.Count; index++)
            {
                var variant = variants[index];
                var uniqueProperty = variant.Properties.FirstOrDefault(property => variants
                    .Where((_, otherIndex) => otherIndex != index)
                    .All(other => other.Properties.All(candidate => candidate.WireName != property.WireName)));
                if (uniqueProperty is null) continue;
                code.Append("        if (value.TryGetProperty(").Append(Literal(uniqueProperty.WireName)).Append(", out _)) return Deserialize")
                    .Append(variant.Name).AppendLine("(value);");
            }
            code.AppendLine("        throw new JsonException(\"Value did not match any union case.\");");
        }
        else
        {
            var variants = model.Cases.Select(caseName => classes.Single(type => type.Name == caseName)).ToArray();
            var discriminator = variants[0].Properties.First(property => property.ConstValue is not null && variants.All(variant =>
                variant.Properties.Any(candidate => candidate.WireName == property.WireName && candidate.ConstValue is not null)));
            code.Append("        return ReadStringValue(Required(value, ").Append(Literal(discriminator.WireName)).AppendLine(")) switch")
                .AppendLine("        {");
            foreach (var variant in variants)
            {
                var constValue = variant.Properties.Single(property => property.WireName == discriminator.WireName).ConstValue!;
                code.Append("            ").Append(Literal(constValue)).Append(" => Deserialize").Append(variant.Name).AppendLine("(value),");
            }
            code.AppendLine("            _ => throw new JsonException(\"Unknown discriminator value.\")")
                .AppendLine("        };");
        }
        code.AppendLine("    }").AppendLine();
    }

    private static void RenderTypedUnionValueReader(StringBuilder code, UnionModel model)
    {
        code.Append("    internal static ").Append(model.Name).Append(" Deserialize").Append(model.Name).AppendLine("(JsonElement value)")
            .AppendLine("    {")
            .Append("        var parsed = Deserialize").Append(model.Name).AppendLine("Value(value);")
            .AppendLine("        return parsed switch")
            .AppendLine("        {");
        for (var index = 0; index < model.Cases.Count; index++)
        {
            code.Append("            ").Append(model.Cases[index]).AppendLine(" item => item,");
        }
        code.AppendLine("            _ => throw new JsonException(\"Value did not match a union case.\")")
            .AppendLine("        };")
            .AppendLine("    }")
            .AppendLine();
    }

    private static void RenderClassReader(StringBuilder code, ClassModel model, IReadOnlyList<ClassModel> classes, IReadOnlyList<UnionModel> unions, bool useSystemTextJson)
    {
        if (model.IsRawPayloadVariant)
        {
            code.Append("    internal static ").Append(model.Name).Append(" Deserialize").Append(model.Name).AppendLine("(JsonElement value) =>")
                .Append("        new ").Append(model.Name).AppendLine(" { RawPayload = value.Clone() };")
                .AppendLine();
            return;
        }
        if (useSystemTextJson)
        {
            code.Append("    internal static ").Append(model.Name).Append(" Deserialize").Append(model.Name).AppendLine("(JsonElement value)")
                .AppendLine("    {")
                .AppendLine("        if (value.ValueKind != JsonValueKind.Object) throw new JsonException(\"Expected a JSON object.\");");
            foreach (var property in model.Properties.Where(property => property.ConstValue is not null))
            {
                code.Append("        if (ReadStringValue(Required(value, ").Append(Literal(property.WireName)).Append(")) != ").Append(Literal(property.ConstValue!)).AppendLine(")")
                    .Append("            throw new JsonException(\"Property '").Append(property.WireName).Append("' must be '").Append(property.ConstValue).AppendLine("'.\");");
            }
            code.Append("        return value.Deserialize(JsonContext.Default.").Append(model.Name).AppendLine(") ?? throw new JsonException(\"Expected a non-null JSON value.\");")
                .AppendLine("    }")
                .AppendLine();
            return;
        }
        code.Append("    internal static ").Append(model.Name).Append(" Deserialize").Append(model.Name).AppendLine("(JsonElement value)")
            .AppendLine("    {")
            .AppendLine("        if (value.ValueKind != JsonValueKind.Object) throw new JsonException(\"Expected a JSON object.\");");
        foreach (var property in model.Properties.Where(property => property.ConstValue is not null))
        {
            code.Append("        if (ReadStringValue(Required(value, ").Append(Literal(property.WireName)).Append(")) != ").Append(Literal(property.ConstValue!)).AppendLine(")")
                .Append("            throw new JsonException(\"Property '").Append(property.WireName).Append("' must be '").Append(property.ConstValue).AppendLine("'.\");");
        }
        code.Append("        return new ").Append(model.Name).AppendLine()
            .AppendLine("        {");
        foreach (var property in model.Properties)
        {
            if (property.ConstValue is not null) continue;
            var type = property.TypeName;
            if (type.EndsWith("?", StringComparison.Ordinal)) type = type.Substring(0, type.Length - 1);
            var valueName = "property_" + property.Identifier;
            var expression = ReadExpression(type, property.WireName, valueName, property.IsRequired, classes, unions);
            code.Append("            ").Append(property.Identifier).Append(" = ").Append(expression).AppendLine(",");
        }
        if (model.HasExtensionData)
        {
            code.Append("            ExtensionData = ReadExtensionData(value");
            foreach (var property in model.Properties) code.Append(", ").Append(Literal(property.WireName));
            code.AppendLine("),");
        }
        code.AppendLine("        };")
            .AppendLine("    }");
        code.AppendLine();
    }

    private static string ReadExpression(string type, string wireName, string valueName, bool required, IReadOnlyList<ClassModel> classes, IReadOnlyList<UnionModel> unions)
    {
        if (required)
        {
            var read = ReadValueExpression(type, valueName, classes, unions);
            return read.Replace(valueName, "Required(value, " + Literal(wireName) + ")");
        }

        var nullableRead = ReadValueExpression(type, valueName, classes, unions);
        return "(value.TryGetProperty(" + Literal(wireName) + ", out var " + valueName + ") && " + valueName + ".ValueKind != JsonValueKind.Null ? " + nullableRead + " : null)";
    }

    private static string ReadValueExpression(string type, string valueName, IReadOnlyList<ClassModel> classes, IReadOnlyList<UnionModel> unions)
    {
        if (type == "string") return "ReadStringValue(" + valueName + ")";
        if (type == "bool") return "ReadBooleanValue(" + valueName + ")";
        if (type == "int") return "ReadInt32Value(" + valueName + ")";
        if (type == "uint") return "ReadUInt32Value(" + valueName + ")";
        if (type == "long") return "ReadInt64Value(" + valueName + ")";
        if (type == "ulong") return "ReadUInt64Value(" + valueName + ")";
        if (type == "double") return "ReadDoubleValue(" + valueName + ")";
        if (type == "float") return "ReadSingleValue(" + valueName + ")";
        if (type == "JsonElement") return valueName + ".Clone()";
        if (type.StartsWith("List<", StringComparison.Ordinal))
        {
            var itemType = type.Substring(5, type.Length - 6);
            return "ReadList(" + valueName + ", static item => " + ReadValueExpression(itemType, "item", classes, unions) + ")";
        }
        if (type == "Dictionary<string, string>") return "ReadStringDictionary(" + valueName + ")";
        if (type == "Dictionary<string, JsonElement>") return "ReadElementDictionary(" + valueName + ")";
        if (classes.Any(item => item.Name == type)) return "Deserialize" + type + "(" + valueName + ")";
        if (unions.Any(item => item.Name == type)) return "Deserialize" + type + "(" + valueName + ")";
        throw new InvalidOperationException("Unsupported generated reader type: " + type);
    }

    private static void RenderTaggedUnionReader(StringBuilder code, ClassModel model, bool useSystemTextJsonContext)
    {
        if (useSystemTextJsonContext)
        {
            code.Append("    internal static ").Append(model.Name).Append(" Deserialize").Append(model.Name).AppendLine("(JsonElement value)")
                .AppendLine("    {");
            if (model.AllowUnknownDiscriminator)
            {
                code.Append("        if (value.ValueKind == JsonValueKind.Object && value.TryGetProperty(")
                    .Append(Literal(model.DiscriminatorName!)).Append(", out var discriminator) && discriminator.ValueKind == JsonValueKind.String && Discriminators.Parse")
                    .Append(model.Name).Append("Discriminator(discriminator.GetString()) == ").Append(model.Name).AppendLine("Discriminator.Unknown)")
                    .Append("            return new ").Append(model.UnknownVariantTypeName).AppendLine(" { RawPayload = value.Clone() };");
            }
            code.Append("        return JsonSerializer.Deserialize(value, JsonContext.Default.").Append(model.Name).AppendLine(") ?? throw new JsonException(\"Expected a non-null JSON value.\");")
                .AppendLine("    }")
                .AppendLine();
            return;
        }

        code.Append("    internal static ").Append(model.Name).Append(" Deserialize").Append(model.Name).AppendLine("(JsonElement value)")
            .AppendLine("    {")
            .Append("        return ReadStringValue(Required(value, ").Append(Literal(model.DiscriminatorName!)).AppendLine(")) switch")
            .AppendLine("        {");
        foreach (var item in model.DiscriminatorCases)
            code.Append("            ").Append(Literal(item.DiscriminatorValue)).Append(" => Deserialize").Append(item.TypeName).AppendLine("(value),");
        if (model.AllowUnknownDiscriminator)
            code.Append("            _ => new ").Append(model.UnknownVariantTypeName).AppendLine(" { RawPayload = value.Clone() },");
        else
            code.AppendLine("            _ => throw new JsonException(\"Unknown discriminator value.\"),");
        code.AppendLine("        };" )
            .AppendLine("    }")
            .AppendLine();
    }

    private static void RenderSystemTextJsonUnionReader(StringBuilder code, UnionModel model)
    {
        code.Append("    internal static ").Append(model.Name).Append(" Deserialize").Append(model.Name).AppendLine("(JsonElement value) =>")
            .Append("        JsonSerializer.Deserialize(value, JsonContext.Default.").Append(model.Name).AppendLine(")!;")
            .AppendLine();
    }

    private static void RenderUnionReader(StringBuilder code, UnionModel model, IReadOnlyList<ClassModel> classes)
    {
        var discriminator = model.Cases
            .Select(caseName => classes.Single(type => type.Name == caseName))
            .SelectMany(type => type.Properties.Where(property => property.ConstValue is not null).Select(property => (property.WireName, property.ConstValue)))
            .GroupBy(property => property.WireName, StringComparer.Ordinal)
            .FirstOrDefault(group => group.Count() == model.Cases.Count && group.Select(item => item.ConstValue).Distinct(StringComparer.Ordinal).Count() == model.Cases.Count);
        if (discriminator is null) return;

        code.Append("    internal static ").Append(model.Name).Append(" Deserialize").Append(model.Name).AppendLine("(JsonElement value)")
            .AppendLine("    {")
            .Append("        return ReadStringValue(Required(value, ").Append(Literal(discriminator.Key)).AppendLine(")) switch")
            .AppendLine("        {");
        foreach (var caseName in model.Cases)
        {
            var type = classes.Single(item => item.Name == caseName);
            var constProperty = type.Properties.Single(property => property.WireName == discriminator.Key);
            code.Append("            ").Append(Literal(constProperty.ConstValue!)).Append(" => Deserialize").Append(caseName).AppendLine("(value),");
        }
        code.AppendLine("            _ => throw new JsonException(\"Unknown discriminator value.\")")
            .AppendLine("        };" )
            .AppendLine("    }")
            .AppendLine();
    }

    private static void RenderClassWriter(
        StringBuilder code,
        ClassModel model,
        IReadOnlyList<ClassModel> classes,
        IReadOnlyList<UnionModel> unions)
    {
        code.Append("    private static void Write").Append(model.Name).Append("(Utf8JsonWriter writer, ").Append(model.Name).AppendLine(" value)")
            .AppendLine("    {");
        if (model.IsRawPayloadVariant)
        {
            code.AppendLine("        value.RawPayload.WriteTo(writer);")
                .AppendLine("    }")
                .AppendLine();
            return;
        }
        if (model.DiscriminatorName is not null)
        {
            if (model.AllowUnknownDiscriminator)
            {
                code.Append("        if (value is ").Append(model.UnknownVariantTypeName).AppendLine(" unknown)")
                    .AppendLine("        {")
                    .AppendLine("            unknown.RawPayload.WriteTo(writer);")
                    .AppendLine("            return;")
                    .AppendLine("        }");
            }
            code.AppendLine("        writer.WriteStartObject();")
                .AppendLine("        switch (value)")
                .AppendLine("        {");
            foreach (var item in model.DiscriminatorCases)
            {
                var derived = classes.Single(type => type.Name == item.TypeName);
                code.Append("            case ").Append(item.TypeName).Append(" derived:").AppendLine()
                    .Append("                writer.WriteString(").Append(Literal(model.DiscriminatorName)).Append(", ").Append(Literal(item.DiscriminatorValue)).AppendLine(");");
                RenderProperties(code, derived, classes, unions, "derived", "                ");
                code.AppendLine("                break;");
            }
            code.AppendLine("            default: throw new ArgumentOutOfRangeException(nameof(value));")
                .AppendLine("        }")
                .AppendLine("        writer.WriteEndObject();");
        }
        else
        {
            code.AppendLine("        writer.WriteStartObject();");
            RenderProperties(code, model, classes, unions, "value", "        ");
            code.AppendLine("        writer.WriteEndObject();");
        }
        code.AppendLine("    }").AppendLine();
    }

    private static void RenderProperties(
        StringBuilder code,
        ClassModel model,
        IReadOnlyList<ClassModel> classes,
        IReadOnlyList<UnionModel> unions,
        string instance,
        string indent)
    {
        foreach (var property in model.Properties)
        {
            var expression = instance + "." + property.Identifier;
            if (property.TypeName.EndsWith("?", StringComparison.Ordinal))
            {
                if (!property.IsRequired)
                {
                    code.Append(indent).Append("if (").Append(expression).AppendLine(" is not null)")
                        .Append(indent).AppendLine("{")
                        .Append(indent).Append("    writer.WritePropertyName(").Append(Literal(property.WireName)).AppendLine(");");
                    var optionalType = property.TypeName.Substring(0, property.TypeName.Length - 1);
                    var optionalExpression = IsValueType(optionalType, unions) ? expression + ".Value" : expression + "!";
                    RenderWriteValue(code, optionalType, optionalExpression, classes, unions, indent + "    ");
                    code.Append(indent).AppendLine("}");
                    continue;
                }
                code.Append(indent).Append("writer.WritePropertyName(").Append(Literal(property.WireName)).AppendLine(");")
                    .Append(indent).Append("if (").Append(expression).AppendLine(" is null) writer.WriteNullValue();")
                    .Append(indent).AppendLine("else")
                    .Append(indent).AppendLine("{");
                var nonNullableType = property.TypeName.Substring(0, property.TypeName.Length - 1);
                var nonNullableExpression = IsValueType(nonNullableType, unions) ? expression + ".Value" : expression + "!";
                RenderWriteValue(code, nonNullableType, nonNullableExpression, classes, unions, indent + "    ");
                code.Append(indent).AppendLine("}");
                continue;
            }

            code.Append(indent).Append("writer.WritePropertyName(").Append(Literal(property.WireName)).AppendLine(");");
            RenderWriteValue(code, property.TypeName, expression, classes, unions, indent);
        }

        if (model.HasExtensionData)
        {
            code.Append(indent).Append("if (").Append(instance).AppendLine(".ExtensionData is not null)")
                .Append(indent).AppendLine("{")
                .Append(indent).Append("    foreach (var item in ").Append(instance).AppendLine(".ExtensionData)")
                .Append(indent).AppendLine("    {")
                .Append(indent).AppendLine("        writer.WritePropertyName(item.Key);")
                .Append(indent).AppendLine("        item.Value.WriteTo(writer);")
                .Append(indent).AppendLine("    }")
                .Append(indent).AppendLine("}");
        }
    }

    private static void RenderWriteValue(
        StringBuilder code,
        string type,
        string expression,
        IReadOnlyList<ClassModel> classes,
        IReadOnlyList<UnionModel> unions,
        string indent)
    {
        if (type.StartsWith("List<", StringComparison.Ordinal))
        {
            var elementType = type.Substring(5, type.Length - 6);
            code.Append(indent).AppendLine("writer.WriteStartArray();")
                .Append(indent).Append("foreach (var item in ").Append(expression).AppendLine(")")
                .Append(indent).AppendLine("{");
            RenderWriteValue(code, elementType, "item", classes, unions, indent + "    ");
            code.Append(indent).AppendLine("}")
                .Append(indent).AppendLine("writer.WriteEndArray();");
            return;
        }
        if (type.StartsWith("Dictionary<string, ", StringComparison.Ordinal))
        {
            var valueType = type.Substring(19, type.Length - 20).Trim();
            code.Append(indent).AppendLine("writer.WriteStartObject();")
                .Append(indent).Append("foreach (var item in ").Append(expression).AppendLine(")")
                .Append(indent).AppendLine("{")
                .Append(indent).AppendLine("    writer.WritePropertyName(item.Key);");
            RenderWriteValue(code, valueType, "item.Value", classes, unions, indent + "    ");
            code.Append(indent).AppendLine("}")
                .Append(indent).AppendLine("writer.WriteEndObject();");
            return;
        }
        if (type == "JsonElement")
        {
            code.Append(indent).Append(expression).AppendLine(".WriteTo(writer);");
            return;
        }
        if (type == "string") { code.Append(indent).Append("writer.WriteStringValue(").Append(expression).AppendLine(");"); return; }
        if (type == "bool") { code.Append(indent).Append("writer.WriteBooleanValue(").Append(expression).AppendLine(");"); return; }
        if (type is "int" or "uint" or "long" or "ulong" or "double" or "float") { code.Append(indent).Append("writer.WriteNumberValue(").Append(expression).AppendLine(");"); return; }
        if (classes.Any(item => item.Name == type)) { code.Append(indent).Append("Write").Append(type).Append("(writer, ").Append(expression).AppendLine(");"); return; }
        if (unions.Any(item => item.Name == type)) { code.Append(indent).Append("Write").Append(type).Append("(writer, ").Append(expression).AppendLine(");"); return; }
        code.Append(indent).Append("Write").Append(type).Append("(writer, ").Append(expression).AppendLine(");");
    }

    private static void RenderEnumWriter(StringBuilder code, EnumModel model)
    {
        code.Append("    private static void Write").Append(model.Name).Append("(Utf8JsonWriter writer, ").Append(model.Name).AppendLine(" value)")
            .AppendLine("    {")
            .AppendLine("        writer.WriteStringValue(value switch")
            .AppendLine("        {");
        foreach (var value in model.Values)
        {
            var identifier = Pascal(value);
            if (string.IsNullOrEmpty(identifier)) identifier = "Value";
            code.Append("            ").Append(model.Name).Append('.').Append(identifier).Append(" => ").Append(Literal(value)).AppendLine(",");
        }
        code.AppendLine("            _ => throw new ArgumentOutOfRangeException(nameof(value))")
            .AppendLine("        });")
            .AppendLine("    }")
            .AppendLine();
    }

    private static void RenderUnionWriter(
        StringBuilder code,
        UnionModel model,
        IReadOnlyList<ClassModel> classes,
        IReadOnlyList<UnionModel> unions)
    {
        code.Append("    private static void Write").Append(model.Name).Append("(Utf8JsonWriter writer, ").Append(model.Name).AppendLine(" value)")
            .AppendLine("    {");
        code.AppendLine("        switch (value)")
            .AppendLine("        {");
        for (var index = 0; index < model.Cases.Count; index++)
        {
            var caseName = model.Cases[index];
            code.Append("            case ").Append(caseName).Append(" caseValue:").AppendLine();
            RenderWriteValue(code, caseName, "caseValue", classes, unions, "                ");
            code.AppendLine("                break;");
        }
        code.AppendLine("            default: throw new ArgumentOutOfRangeException(nameof(value));")
            .AppendLine("        }")
            .AppendLine("    }")
            .AppendLine();
    }

    private static bool IsValueType(string type, IReadOnlyList<UnionModel> unions) =>
        type is "bool" or "int" or "uint" or "long" or "ulong" or "double" or "float" or "JsonElement" || unions.Any(item => item.Name == type);

    private static string Literal(string value) => "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";

    private static string Pascal(string value) => string.Concat(value.Split(new[] { '_', '-', '.', ' ' }, StringSplitOptions.RemoveEmptyEntries).Select(part => char.ToUpperInvariant(part[0]) + part.Substring(1)));
}
