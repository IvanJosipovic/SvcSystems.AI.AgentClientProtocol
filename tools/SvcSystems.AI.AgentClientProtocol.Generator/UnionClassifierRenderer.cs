using System.Text;
using Microsoft.CodeAnalysis.CSharp;

namespace SvcSystems.AI.AgentClientProtocol.Generator;

internal static class UnionClassifierRenderer
{
    private const string Header = "// <auto-generated />\n#pragma warning disable CS1591\n#nullable enable\n";

    public static string FactoryName(SchemaModel model, SchemaGeneratorOptions options)
    {
        var candidate = Identifier(options.JsonContextName + "UnionClassifierFactory");
        while (model.Types.Any(type => type.Name == candidate)) candidate += "_";
        return candidate;
    }

    public static string Render(
        SchemaModel model,
        SchemaGeneratorOptions options,
        IReadOnlyList<string> modelNamespaces)
    {
        var unions = model.Types.OfType<UnionModel>().Where(union => union.HasGeneratedClassifier).ToArray();
        var code = new StringBuilder(Header)
            .AppendLine("using System;")
            .AppendLine("using System.Collections.Generic;")
            .AppendLine("using System.Text.Json;")
            .AppendLine("using System.Text.Json.Serialization;");
        foreach (var modelNamespace in modelNamespaces)
        {
            if (modelNamespace != options.SerializationNamespace)
                code.Append("using global::").Append(modelNamespace).AppendLine(";");
        }
        code.AppendLine()
            .Append("namespace ").Append(options.SerializationNamespace).AppendLine(";")
            .AppendLine()
            .Append("internal sealed class ").Append(FactoryName(model, options)).AppendLine(" : JsonTypeClassifierFactory")
            .AppendLine("{")
            .AppendLine("    private static readonly Dictionary<Type, UnionClassifierDefinition> Definitions = new()")
            .AppendLine("    {");

        foreach (var union in unions)
        {
            RenderDefinition(code, union);
        }

        code.AppendLine("    };")
            .AppendLine()
            .Append("    public ").Append(FactoryName(model, options)).AppendLine("() { }")
            .AppendLine()
            .AppendLine("    public override bool CanClassify(JsonTypeClassifierContext context) =>")
            .AppendLine("        context.Kind == JsonTypeClassifierKind.Union && Definitions.ContainsKey(context.DeclaringType);")
            .AppendLine()
            .AppendLine("    public override JsonTypeClassifier CreateJsonClassifier(JsonTypeClassifierContext context, JsonSerializerOptions options)")
            .AppendLine("    {")
            .AppendLine("        if (!Definitions.TryGetValue(context.DeclaringType, out var definition))")
            .AppendLine("            throw new InvalidOperationException($\"No generated union classifier exists for '{context.DeclaringType}'.\");")
            .AppendLine()
            .AppendLine("        return (ref Utf8JsonReader reader) => Classify(ref reader, definition);")
            .AppendLine("    }")
            .AppendLine()
            .AppendLine("    private static Type? Classify(ref Utf8JsonReader reader, UnionClassifierDefinition definition)")
            .AppendLine("    {")
            .AppendLine("        var stringCase = FindCase(definition, typeof(string));")
            .AppendLine("        if (stringCase is not null && reader.TokenType == JsonTokenType.String) return stringCase;")
            .AppendLine()
            .AppendLine("        var booleanCase = FindCase(definition, typeof(bool));")
            .AppendLine("        if (booleanCase is not null && reader.TokenType is JsonTokenType.True or JsonTokenType.False) return booleanCase;")
            .AppendLine()
            .AppendLine("        if (reader.TokenType == JsonTokenType.Number && definition.NumericCases.Length > 0)")
            .AppendLine("        {")
            .AppendLine("            if (definition.NumericCases.Length == 1) return definition.NumericCases[0];")
            .AppendLine("            foreach (var numericCase in definition.IntegerCases)")
            .AppendLine("            {")
            .AppendLine("                if (TryReadInteger(ref reader, numericCase)) return numericCase;")
            .AppendLine("            }")
            .AppendLine("            foreach (var numericCase in definition.FloatingPointCases)")
            .AppendLine("            {")
            .AppendLine("                if (TryReadFloatingPoint(ref reader, numericCase)) return numericCase;")
            .AppendLine("            }")
            .AppendLine("            return GetRawFallback(definition);")
            .AppendLine("        }")
            .AppendLine()
            .AppendLine("        if (reader.TokenType == JsonTokenType.StartArray)")
            .AppendLine("        {")
            .AppendLine("            if (definition.AllCasesAreLists) return ClassifyArray(ref reader, definition);")
            .AppendLine("            if (definition.ListCases.Length == 1) return definition.ListCases[0];")
            .AppendLine("        }")
            .AppendLine()
            .AppendLine("        if (reader.TokenType != JsonTokenType.StartObject) return GetRawFallback(definition);")
            .AppendLine("        return ClassifyObject(ref reader, definition);")
            .AppendLine("    }")
            .AppendLine()
            .AppendLine("    private static Type? ClassifyObject(ref Utf8JsonReader reader, UnionClassifierDefinition definition)")
            .AppendLine("    {")
            .AppendLine("        var matchedCase = -1;")
            .AppendLine("        var observedProperties = definition.NeedsStructuralFallback ? new HashSet<string>(StringComparer.Ordinal) : null;")
            .AppendLine("        while (reader.Read() && reader.TokenType != JsonTokenType.EndObject)")
            .AppendLine("        {")
            .AppendLine("            if (reader.TokenType != JsonTokenType.PropertyName) continue;")
            .AppendLine("            if (observedProperties is not null && reader.GetString() is { } propertyName) observedProperties.Add(propertyName);")
            .AppendLine("            if (definition.DiscriminatorProperty is { } discriminatorProperty && reader.ValueTextEquals(discriminatorProperty))")
            .AppendLine("            {")
            .AppendLine("                if (!reader.Read() || reader.TokenType != JsonTokenType.String) return null;")
            .AppendLine("                var discriminatorValue = reader.GetString();")
            .AppendLine("                if (discriminatorValue is not null && definition.DiscriminatorCases.TryGetValue(discriminatorValue, out var caseType)) return caseType;")
            .AppendLine("                return definition.RawFallbackCase ?? definition.TagFallbackCase ?? definition.UnknownDiscriminatorFallbackCase;")
            .AppendLine("            }")
            .AppendLine()
            .AppendLine("            if (definition.NeedsStructuralFallback)")
            .AppendLine("            {")
            .AppendLine("                for (var index = 0; index < definition.Cases.Length; index++)")
            .AppendLine("                {")
            .AppendLine("                    if (!definition.Cases[index].ContainsUniqueProperty(reader)) continue;")
            .AppendLine("                    if (matchedCase >= 0 && matchedCase != index) return null;")
            .AppendLine("                    matchedCase = index;")
            .AppendLine("                }")
            .AppendLine("            }")
            .AppendLine()
            .AppendLine("            if (!reader.Read()) return null;")
            .AppendLine("            reader.Skip();")
            .AppendLine("        }")
            .AppendLine()
            .AppendLine("        if (definition.AllowUnknownDiscriminator) return null;")
            .AppendLine("        if (definition.DiscriminatorProperty is not null && definition.DefaultCase is not null) return definition.DefaultCase;")
            .AppendLine("        if (definition.DiscriminatorIsComplete) return null;")
            .AppendLine("        if (matchedCase >= 0) return definition.Cases[matchedCase].CaseType;")
            .AppendLine("        if (observedProperties is not null)")
            .AppendLine("        {")
            .AppendLine("            var requiredMatch = -1;")
            .AppendLine("            for (var index = 0; index < definition.Cases.Length; index++)")
            .AppendLine("            {")
            .AppendLine("                if (!definition.Cases[index].HasAllRequiredProperties(observedProperties)) continue;")
            .AppendLine("                if (requiredMatch >= 0) return null;")
            .AppendLine("                requiredMatch = index;")
            .AppendLine("            }")
            .AppendLine("            if (requiredMatch >= 0) return definition.Cases[requiredMatch].CaseType;")
            .AppendLine("        }")
            .AppendLine("        return definition.RawFallbackCase ?? definition.DefaultCase;")
            .AppendLine("    }")
            .AppendLine()
            .AppendLine("    private static Type? ClassifyArray(ref Utf8JsonReader reader, UnionClassifierDefinition definition)")
            .AppendLine("    {")
            .AppendLine("        if (!reader.Read()) return null;")
            .AppendLine("        if (reader.TokenType == JsonTokenType.EndArray) return definition.DefaultCase ?? definition.CaseTypes[0];")
            .AppendLine("        if (reader.TokenType != JsonTokenType.StartObject) return null;")
            .AppendLine()
            .AppendLine("        var matchedCase = -1;")
            .AppendLine("        var observedProperties = new HashSet<string>(StringComparer.Ordinal);")
            .AppendLine("        while (reader.Read() && reader.TokenType != JsonTokenType.EndObject)")
            .AppendLine("        {")
            .AppendLine("            if (reader.TokenType != JsonTokenType.PropertyName) continue;")
            .AppendLine("            if (reader.GetString() is { } propertyName) observedProperties.Add(propertyName);")
            .AppendLine("            for (var index = 0; index < definition.Cases.Length; index++)")
            .AppendLine("            {")
            .AppendLine("                if (!definition.Cases[index].ContainsUniqueProperty(reader)) continue;")
            .AppendLine("                if (matchedCase >= 0 && matchedCase != index) return null;")
            .AppendLine("                matchedCase = index;")
            .AppendLine("            }")
            .AppendLine("            if (!reader.Read()) return null;")
            .AppendLine("            reader.Skip();")
            .AppendLine("        }")
            .AppendLine()
            .AppendLine("        if (matchedCase >= 0) return definition.Cases[matchedCase].CaseType;")
            .AppendLine("        var requiredMatch = -1;")
            .AppendLine("        for (var index = 0; index < definition.Cases.Length; index++)")
            .AppendLine("        {")
            .AppendLine("            if (!definition.Cases[index].HasAllRequiredProperties(observedProperties)) continue;")
            .AppendLine("            if (requiredMatch >= 0) return null;")
            .AppendLine("            requiredMatch = index;")
            .AppendLine("        }")
            .AppendLine("        if (requiredMatch >= 0) return definition.Cases[requiredMatch].CaseType;")
            .AppendLine("        return definition.DefaultCase;")
            .AppendLine("    }")
            .AppendLine()
            .AppendLine("    private static Type? GetRawFallback(UnionClassifierDefinition definition) =>")
            .AppendLine("        definition.RawFallbackCase is not null && !definition.AllowUnknownDiscriminator ? definition.RawFallbackCase : null;")
            .AppendLine()
            .AppendLine("    private static Type? FindCase(UnionClassifierDefinition definition, Type type)")
            .AppendLine("    {")
            .AppendLine("        foreach (var caseType in definition.CaseTypes)")
            .AppendLine("        {")
            .AppendLine("            if (caseType == type) return caseType;")
            .AppendLine("        }")
            .AppendLine("        return null;")
            .AppendLine("    }")
            .AppendLine()
            .AppendLine("    private static bool TryReadInteger(ref Utf8JsonReader reader, Type type) =>")
            .AppendLine("        type == typeof(int) ? reader.TryGetInt32(out _) :")
            .AppendLine("        type == typeof(uint) ? reader.TryGetUInt32(out _) :")
            .AppendLine("        type == typeof(long) ? reader.TryGetInt64(out _) :")
            .AppendLine("        type == typeof(ulong) && reader.TryGetUInt64(out _);")
            .AppendLine()
            .AppendLine("    private static bool TryReadFloatingPoint(ref Utf8JsonReader reader, Type type) =>")
            .AppendLine("        type == typeof(float) ? reader.TryGetSingle(out _) :")
            .AppendLine("        type == typeof(double) && reader.TryGetDouble(out _);")
            .AppendLine()
            .AppendLine("    private sealed class UnionClassifierDefinition(")
            .AppendLine("        Type[] caseTypes,")
            .AppendLine("        Type[] numericCases,")
            .AppendLine("        Type[] integerCases,")
            .AppendLine("        Type[] floatingPointCases,")
            .AppendLine("        Type[] listCases,")
            .AppendLine("        bool allCasesAreLists,")
            .AppendLine("        string? discriminatorProperty,")
            .AppendLine("        Dictionary<string, Type> discriminatorCases,")
            .AppendLine("        Type? tagFallbackCase,")
            .AppendLine("        Type? rawFallbackCase,")
            .AppendLine("        Type? unknownDiscriminatorFallbackCase,")
            .AppendLine("        Type? defaultCase,")
            .AppendLine("        bool allowUnknownDiscriminator,")
            .AppendLine("        bool discriminatorIsComplete,")
            .AppendLine("        bool needsStructuralFallback,")
            .AppendLine("        UnionCaseClassifierDefinition[] cases)")
            .AppendLine("    {")
            .AppendLine("        public Type[] CaseTypes { get; } = caseTypes;")
            .AppendLine("        public Type[] NumericCases { get; } = numericCases;")
            .AppendLine("        public Type[] IntegerCases { get; } = integerCases;")
            .AppendLine("        public Type[] FloatingPointCases { get; } = floatingPointCases;")
            .AppendLine("        public Type[] ListCases { get; } = listCases;")
            .AppendLine("        public bool AllCasesAreLists { get; } = allCasesAreLists;")
            .AppendLine("        public string? DiscriminatorProperty { get; } = discriminatorProperty;")
            .AppendLine("        public Dictionary<string, Type> DiscriminatorCases { get; } = discriminatorCases;")
            .AppendLine("        public Type? TagFallbackCase { get; } = tagFallbackCase;")
            .AppendLine("        public Type? RawFallbackCase { get; } = rawFallbackCase;")
            .AppendLine("        public Type? UnknownDiscriminatorFallbackCase { get; } = unknownDiscriminatorFallbackCase;")
            .AppendLine("        public Type? DefaultCase { get; } = defaultCase;")
            .AppendLine("        public bool AllowUnknownDiscriminator { get; } = allowUnknownDiscriminator;")
            .AppendLine("        public bool DiscriminatorIsComplete { get; } = discriminatorIsComplete;")
            .AppendLine("        public bool NeedsStructuralFallback { get; } = needsStructuralFallback;")
            .AppendLine("        public UnionCaseClassifierDefinition[] Cases { get; } = cases;")
            .AppendLine("    }")
            .AppendLine()
            .AppendLine("    private sealed class UnionCaseClassifierDefinition(Type caseType, string[] requiredProperties, string[] uniqueProperties)")
            .AppendLine("    {")
            .AppendLine("        public Type CaseType { get; } = caseType;")
            .AppendLine("        public bool HasAllRequiredProperties(HashSet<string> propertyNames)")
            .AppendLine("        {")
            .AppendLine("            if (RequiredProperties.Length == 0) return false;")
            .AppendLine("            foreach (var property in RequiredProperties)")
            .AppendLine("            {")
            .AppendLine("                if (!propertyNames.Contains(property)) return false;")
            .AppendLine("            }")
            .AppendLine("            return true;")
            .AppendLine("        }")
            .AppendLine("        public bool ContainsUniqueProperty(Utf8JsonReader reader)")
            .AppendLine("        {")
            .AppendLine("            foreach (var property in UniqueProperties)")
            .AppendLine("            {")
            .AppendLine("                if (reader.ValueTextEquals(property)) return true;")
            .AppendLine("            }")
            .AppendLine("            return false;")
            .AppendLine("        }")
            .AppendLine("        private string[] RequiredProperties { get; } = requiredProperties;")
            .AppendLine("        private string[] UniqueProperties { get; } = uniqueProperties;")
            .AppendLine("    }")
            .AppendLine("}");

        return code.ToString();
    }

    private static void RenderDefinition(StringBuilder code, UnionModel union)
    {
        var discriminatorProperty = union.DiscriminatorProperty;
        var discriminatorCases = new List<(string Value, string TypeName)>();
        if (discriminatorProperty is not null)
        {
            foreach (var caseModel in union.CaseModels)
            {
                if (caseModel.ConstProperties.TryGetValue(discriminatorProperty, out var constValue))
                    discriminatorCases.Add((constValue, caseModel.TypeName));
            }
        }
        var tagFallback = discriminatorProperty is null
            ? null
            : union.CaseModels.FirstOrDefault(item =>
                item.TypeName != union.DefaultCaseName &&
                item.Properties.Contains(discriminatorProperty, StringComparer.Ordinal) &&
                item.RequiredProperties.Contains(discriminatorProperty, StringComparer.Ordinal) &&
                !item.ConstProperties.ContainsKey(discriminatorProperty));
        var rawFallback = union.Cases.FirstOrDefault(item => item == "JsonElement");
        var discriminatorIsComplete = discriminatorProperty is not null &&
            (union.DefaultCaseName is not null || union.CaseModels.All(item =>
                item.RequiredProperties.Contains(discriminatorProperty, StringComparer.Ordinal)));
        var needsStructuralFallback = !union.AllowUnknownDiscriminator && !discriminatorIsComplete;
        var numericCases = union.Cases.Where(IsNumericType).ToArray();
        var integerCases = numericCases.Where(IsIntegerType).OrderBy(GetNumericWidth).ToArray();
        var floatingPointCases = numericCases.Where(IsFloatingPointType).OrderByDescending(GetNumericWidth).ToArray();
        var listCases = union.Cases.Where(item => item.StartsWith("List<", StringComparison.Ordinal)).ToArray();
        var allCasesAreLists = union.Cases.All(item => item.StartsWith("List<", StringComparison.Ordinal));

        code.Append("        [typeof(").Append(union.Name).AppendLine(")] = new(")
            .Append("            new Type[] { ").Append(string.Join(", ", union.Cases.Select(TypeOf))).AppendLine(" },")
            .Append("            new Type[] { ").Append(string.Join(", ", numericCases.Select(TypeOf))).AppendLine(" },")
            .Append("            new Type[] { ").Append(string.Join(", ", integerCases.Select(TypeOf))).AppendLine(" },")
            .Append("            new Type[] { ").Append(string.Join(", ", floatingPointCases.Select(TypeOf))).AppendLine(" },")
            .Append("            new Type[] { ").Append(string.Join(", ", listCases.Select(TypeOf))).AppendLine(" },")
            .Append("            ").Append(allCasesAreLists ? "true" : "false").AppendLine(",")
            .Append("            ").Append(discriminatorProperty is null ? "null" : Literal(discriminatorProperty)).AppendLine(",")
            .AppendLine("            new Dictionary<string, Type>(StringComparer.Ordinal)")
            .AppendLine("            {");
        foreach (var item in discriminatorCases)
        {
            code.Append("                [").Append(Literal(item.Value)).Append("] = ").Append(TypeOf(item.TypeName)).AppendLine(",");
        }
        code.AppendLine("            },")
            .Append("            ").Append(tagFallback is null ? "null" : TypeOf(tagFallback.TypeName)).AppendLine(",")
            .Append("            ").Append(rawFallback is null ? "null" : TypeOf(rawFallback)).AppendLine(",")
            .Append("            ").Append(union.UnknownDiscriminatorFallbackCaseName is null ? "null" : TypeOf(union.UnknownDiscriminatorFallbackCaseName)).AppendLine(",")
            .Append("            ").Append(union.DefaultCaseName is null ? "null" : TypeOf(union.DefaultCaseName)).AppendLine(",")
            .Append("            ").Append(union.AllowUnknownDiscriminator ? "true" : "false").AppendLine(",")
            .Append("            ").Append(discriminatorIsComplete ? "true" : "false").AppendLine(",")
            .Append("            ").Append(needsStructuralFallback ? "true" : "false").AppendLine(",")
            .AppendLine("            new UnionCaseClassifierDefinition[]")
            .AppendLine("            {");
        foreach (var caseModel in union.CaseModels)
        {
            code.Append("                new(")
                .Append(TypeOf(caseModel.TypeName)).Append(", new string[] { ")
                .Append(string.Join(", ", caseModel.RequiredProperties.Select(Literal)))
                .Append(" }, new string[] { ")
                .Append(string.Join(", ", caseModel.UniqueProperties.Select(Literal)))
                .AppendLine(" }),");
        }
        code.AppendLine("            }),");
    }

    private static string TypeOf(string typeName) => "typeof(" + typeName + ")";

    private static string Literal(string value) => SymbolDisplay.FormatLiteral(value, quote: true);

    private static bool IsNumericType(string typeName) =>
        typeName is "int" or "uint" or "long" or "ulong" or "double" or "float";

    private static bool IsIntegerType(string typeName) =>
        typeName is "int" or "uint" or "long" or "ulong";

    private static bool IsFloatingPointType(string typeName) =>
        typeName is "float" or "double";

    private static int GetNumericWidth(string typeName) =>
        typeName is "int" or "uint" or "float" ? 32 : 64;

    private static string Identifier(string value)
    {
        var result = new string(value.Select(character => char.IsLetterOrDigit(character) || character == '_' ? character : '_').ToArray());
        if (result.Length == 0 || !char.IsLetter(result[0]) && result[0] != '_') result = "_" + result;
        return result;
    }
}
